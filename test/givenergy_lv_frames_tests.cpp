TEST(GivEnergyLvFrames, CrcMatchesTheCapturedPoll) {
  // Modbus sends the CRC low byte first: 44 03 is 0x0344.
  EXPECT_EQ(givenergy_lv::crc16(kHrPoll.data(), 6), 0x0344);
}

TEST(GivEnergyLvFrames, RecognisesCapturedRequests) {
  EXPECT_TRUE(givenergy_lv::is_request(kHrPoll.data()));
  const uint8_t block2_device5[] = {0x05, 0x04, 0x00, 0x15, 0x00, 0x13, 0xA1, 0x87};
  EXPECT_TRUE(givenergy_lv::is_request(block2_device5));
}

TEST(GivEnergyLvFrames, RejectsBadCrcAndOtherFunctions) {
  std::vector<uint8_t> corrupted = kHrPoll;
  corrupted[5] = 0x1D;
  EXPECT_FALSE(givenergy_lv::is_request(corrupted.data()));
  // FC16 with a valid CRC: the battery never answers it.
  EXPECT_FALSE(givenergy_lv::is_request(with_crc({0x01, 0x10, 0x00, 0x00, 0x00, 0x01}).data()));
}

TEST(GivEnergyLvFrames, FullHoldingPollMatchesCapture) {
  EXPECT_EQ(reply_to(kHrPoll, captured_snapshot()), kCapturedHr);
}

TEST(GivEnergyLvFrames, ShortPollReturnsHr17ToHr25) {
  // The ARM switches to this poll when HR109 is not 1.
  std::vector<uint8_t> expected = {0x01, 0x03, 18};
  expected.insert(expected.end(), kCapturedHr.begin() + 3 + 34, kCapturedHr.begin() + 3 + 52);
  EXPECT_EQ(reply_to(with_crc({0x01, 0x03, 0x00, 0x11, 0x00, 0x09}), captured_snapshot()), with_crc(expected));
}

TEST(GivEnergyLvFrames, PollPastHr27IsRejected) {
  EXPECT_EQ(reply_to(with_crc({0x01, 0x03, 0x00, 0x10, 0x00, 0x0D}), captured_snapshot()),
            with_crc({0x01, 0x83, 0x02}));
}

TEST(GivEnergyLvFrames, HoldingPollToAnEmptySlotGetsNoReply) {
  EXPECT_TRUE(reply_to(with_crc({0x02, 0x03, 0x00, 0x00, 0x00, 0x1C}), captured_snapshot()).empty());
}

TEST(GivEnergyLvFrames, PackBlocksMatchCapture) {
  const givenergy_lv::Snapshot s = captured_snapshot();
  EXPECT_EQ(reply_to(kBlock1Poll, s), kCapturedBlock1);
  EXPECT_EQ(reply_to(kBlock2Poll, s), kCapturedBlock2);
  EXPECT_EQ(reply_to(kBlock3Poll, s), kCapturedBlock3);
}

TEST(GivEnergyLvFrames, EmptySlotsMatchCapture) {
  const givenergy_lv::Snapshot s = captured_snapshot();
  EXPECT_EQ(reply_to({0x02, 0x04, 0x00, 0x00, 0x00, 0x15, 0x31, 0xF6}, s), kCapturedEmptyBlock1Device2);
  EXPECT_EQ(reply_to({0x03, 0x04, 0x00, 0x15, 0x00, 0x13, 0xA1, 0xE1}, s), kCapturedEmptyBlock2Device3);
  EXPECT_EQ(reply_to({0x04, 0x04, 0x00, 0x28, 0x00, 0x14, 0x70, 0x58}, s), kCapturedEmptyBlock3Device4);
}

TEST(GivEnergyLvFrames, UnknownInputRangeIsRejected) {
  EXPECT_EQ(reply_to(with_crc({0x01, 0x04, 0x00, 0x10, 0x00, 0x04}), captured_snapshot()),
            with_crc({0x01, 0x84, 0x02}));
}

TEST(GivEnergyLvFrames, NegativeTemperaturesAreTwosComplement) {
  givenergy_lv::Snapshot s = captured_snapshot();
  s.sensor_temps_dC[0] = -52;  // -5.2 °C in a winter garage
  s.temp_min_dC = -52;
  const std::vector<uint8_t> block1 = reply_to(kBlock1Poll, s);
  EXPECT_EQ(block1[4 + 22], 0xFF);
  EXPECT_EQ(block1[4 + 23], 0xCC);
  const std::vector<uint8_t> block3 = reply_to(kBlock3Poll, s);
  EXPECT_EQ(block3[4 + 34], 0xFF);
  EXPECT_EQ(block3[4 + 35], 0xCC);
}

TEST(GivEnergyLvFrames, WritesAreEchoed) {
  // The inverter retries a write until it sees the echo, stalling the bus.
  const std::vector<uint8_t> write = with_crc({0x01, 0x06, 0x00, 0x02, 0x00, 0x01});
  EXPECT_EQ(reply_to(write, captured_snapshot()), write);
}

TEST(GivEnergyLvFrames, DevicesOutsideOneToFiveGetNoReply) {
  EXPECT_TRUE(reply_to(with_crc({0x00, 0x04, 0x00, 0x00, 0x00, 0x15}), captured_snapshot()).empty());
  EXPECT_TRUE(reply_to(with_crc({0x06, 0x04, 0x00, 0x00, 0x00, 0x15}), captured_snapshot()).empty());
  EXPECT_TRUE(reply_to(with_crc({0x06, 0x06, 0x00, 0x02, 0x00, 0x01}), captured_snapshot()).empty());
}

TEST(GivEnergyLvFrames, Block2CapacityIsSentAsA32BitValue) {
  // The inverter firmware reads block 2 bytes 13-16 as a u32 BE, 0.01 Ah - big enough that a
  // 16-bit field would have saturated it.
  givenergy_lv::Snapshot s = captured_snapshot();
  s.full_capacity_cAh = 125000;  // 0x0001E848
  const std::vector<uint8_t> block2 = reply_to(kBlock2Poll, s);
  EXPECT_EQ(block2[4 + 13], 0x00);
  EXPECT_EQ(block2[4 + 14], 0x01);
  EXPECT_EQ(block2[4 + 15], 0xE8);
  EXPECT_EQ(block2[4 + 16], 0x48);
}
