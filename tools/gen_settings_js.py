#!/usr/bin/env python3
"""Gzip the settings-page script into PROGMEM headers.

settings_page.js is the script that used to be inline in SETTINGS_HTML_SCRIPTS, without the
<script> tags. The web server sends it as /settings.js with Content-Encoding: gzip. Two headers
are written so each board takes the copy that matches its build:

  * settings_js_full_autogen.h  — every function, for boards that are not SMALL_FLASH_DEVICE
  * settings_js_small_autogen.h — the same script with the QNHCK calibration function and the
    charger setpoint functions removed, which is what small-flash images used to compile in

Those two blocks are located by anchors that are part of the script itself, so the served bytes
stay identical to the old inline script. The headers are regenerated on every build and are not
committed.

    python tools/gen_settings_js.py --check   # decompress both blobs and compare
"""
import gzip
import pathlib
import re
import sys

PER_LINE = 16

# Anchors are unique lines of the script. Small-flash builds omit everything from each start
# anchor up to, but not including, the matching end anchor.
QNH_START = "\n\n        function calibrateQnhZero()"
QNH_END = "\n        function editTeslaBalAct()"
CHG_START = "\n          function editChargerHVDCEnabled()"
CHG_END = "\n\n          function goToMainPage()"


def small_script(full: str) -> str:
    q0 = full.find(QNH_START)
    q1 = full.find(QNH_END)
    c0 = full.find(CHG_START)
    c1 = full.find(CHG_END)
    if -1 in (q0, q1, c0, c1) or not (q0 < q1 < c0 < c1):
        raise SystemExit("gen_settings_js: settings_page.js is missing the optional script blocks")
    return full[:q0] + full[q1:c0] + full[c1:]


def render_header(raw: bytes, variant: str) -> str:
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(packed), PER_LINE):
        chunk = packed[i : i + PER_LINE]
        lines.append("    " + " ".join(f"0x{b:02X}," for b in chunk))
    body = "\n".join(lines).rstrip(",")
    return (
        "#pragma once\n"
        "\n"
        f"// AUTO-GENERATED by tools/gen_settings_js.py from settings_page.js ({variant}). Do not edit.\n"
        "// Served as /settings.js with Content-Encoding: gzip.\n"
        f"// {len(raw)} bytes of script compress to {len(packed)}.\n"
        "\n"
        "#include <Arduino.h>\n"
        "\n"
        "#define SETTINGS_JS_EMBEDDED\n"
        "// clang-format off\n"
        "static const uint8_t SETTINGS_JS_GZ[] PROGMEM = {\n"
        f"{body}\n"
        "};\n"
        "// clang-format on\n"
    )


def parse_header(text: str) -> bytes:
    return gzip.decompress(bytes(int(b, 16) for b in re.findall(r"0x([0-9A-F]{2})", text)))


def project_paths():
    if env is not None:
        root = pathlib.Path(env.subst("$PROJECT_DIR"))
    else:
        root = pathlib.Path(__file__).resolve().parent.parent
    web = root / "Software" / "src" / "devboard" / "webserver"
    return root, web / "settings_page.js", web / "settings_js_full_autogen.h", web / "settings_js_small_autogen.h"


def variants():
    _, src, _, _ = project_paths()
    full = src.read_text(encoding="utf-8")
    return full.encode("utf-8"), small_script(full).encode("utf-8")


def write_if_changed(path: pathlib.Path, text: str) -> None:
    try:
        old = path.read_text(encoding="utf-8")
    except OSError:
        old = ""
    if old != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def check() -> int:
    _, src, _, _ = project_paths()
    if not src.is_file():
        print(f"gen_settings_js: missing {src}", file=sys.stderr)
        return 1
    full, small = variants()
    if b"function calibrateQnhZero" not in full or b"function editChargerHVDCEnabled" not in full:
        print("gen_settings_js: full script is missing an optional block", file=sys.stderr)
        return 1
    if b"function calibrateQnhZero" in small or b"function editChargerHVDCEnabled" in small:
        print("gen_settings_js: small-flash script still contains an optional block", file=sys.stderr)
        return 1
    for name in (b"askFactoryReset", b"editTeslaBalAct", b"goToMainPage"):
        if name not in full or name not in small:
            print(f"gen_settings_js: {name.decode()} missing from a variant", file=sys.stderr)
            return 1
    for label, raw in (("full", full), ("small-flash", small)):
        served = parse_header(render_header(raw, label))
        if served != raw:
            print(f"gen_settings_js: {label} blob does not decompress to settings_page.js", file=sys.stderr)
            return 1
        print(f"{label}: {len(raw)} bytes -> {len(gzip.compress(raw, compresslevel=9, mtime=0))} gzipped")
    return 0


def generate_headers():
    root, _, full_out, small_out = project_paths()
    full, small = variants()
    write_if_changed(full_out, render_header(full, "full"))
    write_if_changed(small_out, render_header(small, "small-flash"))
    return root, full_out, small_out


env = None
try:
    Import("env")  # noqa: F821 - provided by PlatformIO
except Exception:
    env = None

if env is not None:
    generate_headers()
elif __name__ == "__main__":
    if "--check" in sys.argv[1:]:
        raise SystemExit(check())
    root, full_out, small_out = generate_headers()
    print(f"wrote {full_out.relative_to(root)}")
    print(f"wrote {small_out.relative_to(root)}")
